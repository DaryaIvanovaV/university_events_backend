"""
Актуальность события: не устарело ли оно уже на момент публикации.

Отчёты о прошедшем — самый частый мусор в канале: «вчора завершилася наша
щорічна конференція, дякуємо всім». Модель послушно извлекает оттуда событие
с датой вчерашнего дня, оно ложится в БД как pending, и администратор всё
равно его отклонит: показать такое в календаре нельзя, GET /events?upcoming
фильтрует date >= сегодня. Смысла занимать очередь модерации нет.

СРАВНИВАЕМ С ДАТОЙ ПУБЛИКАЦИИ, а не с сегодняшней. Это принципиально:
  * дата поста → «на момент объявления событие уже прошло» = это отчёт,
    а не анонс. Ровно то, что нужно отсечь;
  * сегодняшняя дата → сломался бы импорт истории (scripts/import_history.py):
    все события из прошлогоднего экспорта оказались бы «устаревшими», хотя
    относительно своих объявлений они были в будущем.

Событие в тот же день, что и объявление («сьогодні о 18:00»), остаётся:
устаревшим считается только строго более ранняя дата.

Событие БЕЗ даты не отсекается: модератор может проставить дату руками
через PATCH, и анонс станет полноценным. Прошедшее так не починить.
"""

from __future__ import annotations

import datetime as dt
import re

from app.models.schemas import ExtractedEvent
from app.services.clock import today

# Отчёт о прошедшем распознаётся отдельно от даты события, потому что дате
# верить нельзя: в сообщении 202 модель ставила дату публикации, а «20
# листопада» из того же текста — это выход сборника, а не сам заход. Признак
# надёжнее даты: прошедшее время глагола «происходить» рядом с указанием на
# прошлое, либо благодарность участникам — она бывает только постфактум.
_PAST_REPORT: tuple[re.Pattern[str], ...] = (
    re.compile(
        r"\b(?:вчора|позавчора|минул\w+\s+(?:тижня|місяця|року)|торік)\b"
        r"[^.!?]{0,60}?"
        r"\b(?:заверш|відбул|пройш|стартув|закінч)\w*",
        re.IGNORECASE,
    ),
    re.compile(
        r"\b(?:заверш|відбул|пройш|закінч)\w*[^.!?]{0,40}?"
        r"\b(?:вчора|позавчора|минул\w+\s+(?:тижня|місяця))\b",
        re.IGNORECASE,
    ),
    re.compile(r"дяку(?:ємо|ю)\s+(?:всім|усім)[,\s]+хто", re.IGNORECASE),
)


def past_report_reason(text: str) -> str | None:
    """Причина считать сообщение отчётом о прошедшем, либо None."""
    for regex in _PAST_REPORT:
        found = regex.search(text)
        if found:
            fragment = " ".join(found.group(0).split())[:60]
            return f"звіт про минуле, а не анонс: «{fragment}»"
    return None


# --- Отменённое событие ---

# «скасовано», «відмінено», «не відбудеться». НЕ «перенесено»: перенос с новой
# датой — это нормальный анонс (сообщение 208: «перенесено з 20 грудня на
# 23 грудня»), его отсекать нельзя.
_CANCELLED = re.compile(
    r"\b(?:скасован\w*|скасовано|відмінен\w*|відмінено)\b"
    r"|\bне\s+відбудеться\b",
    re.IGNORECASE,
)
# Явная дата: число + название месяца либо 15.10. Если такая стоит ПОСЛЕ слова
# «скасовано», значит объявлена замена — событие остаётся.
_DATE_AFTER = re.compile(
    r"\d{1,2}\s*(?:-?го)?\s*(?:[-–—]\s*\d{1,2}\s*)?"
    r"(?:січня|січень|лютого|лютий|березня|березень|квітня|квітень|травня"
    r"|травень|червня|червень|липня|липень|серпня|серпень|вересня|вересень"
    r"|жовтня|жовтень|листопада|листопад|грудня|грудень)\b"
    r"|\b\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\b",
    re.IGNORECASE,
)


def cancelled_reason(text: str) -> str | None:
    """
    Причина считать событие отменённым, либо None.

    Отменённое событие в календаре бесполезно: его либо не будет вовсе, либо
    объявят заново с новой датой. Старую дату сохранять тем более нельзя.

    Перенос с указанием НОВОЙ даты отменой не считается: если после слова
    «скасовано» в тексте есть явная дата, значит замена уже названа.
    """
    found = _CANCELLED.search(text)
    if not found:
        return None
    if _DATE_AFTER.search(text[found.end():]):
        return None  # названа новая дата — это перенос, а не отмена
    fragment = " ".join(found.group(0).split())
    return f"подію скасовано, нової дати немає: «{fragment}»"


# --- Анонс публикации ---

# «Вийшов друком збірник», «опубліковано монографію». Требуется прошедшее
# время глагола издания: сообщение 207 про ДЕДЛАЙН подачи тез тоже содержит
# «збірник наукових праць», но это настоящий анонс, и трогать его нельзя.
_PUBLICATION = re.compile(
    r"\b(?:вийш\w+\s+друком|надійшов\s+друком)\b"
    r"|\b(?:опубліковано|видано|вийшов|вийшла|вийшло)\b[^.!?]{0,40}?"
    r"\b(?:збірник\w*|монографі\w+|видання|випуск|номер\s+журналу)\b",
    re.IGNORECASE,
)


def publication_reason(text: str) -> str | None:
    """Причина считать сообщение анонсом публикации, а не события."""
    found = _PUBLICATION.search(text)
    if not found:
        return None
    fragment = " ".join(found.group(0).split())[:60]
    return f"анонс публікації, а не подія: «{fragment}»"


def stale_reason(
    event: ExtractedEvent,
    reference_date: dt.date | None = None,
    source_text: str = "",
) -> str | None:
    """
    Причина, по которой событие уже неактуально, либо None.

    reference_date — дата публикации сообщения; по умолчанию сегодняшняя
    (так же, как её подставляет EventExtractor.extract).
    """
    text = source_text or ""
    for detector in (past_report_reason, cancelled_reason, publication_reason):
        reason = detector(text)
        if reason is not None:
            return reason

    if event.date is None:
        return None  # дату может проставить модератор — не наш случай
    reference_date = reference_date or today()
    if event.date < reference_date:
        days = (reference_date - event.date).days
        return (
            f"подія вже відбулася: {event.date.isoformat()} — на "
            f"{days} дн. раніше за оголошення ({reference_date.isoformat()})"
        )
    return None


def is_stale(
    event: ExtractedEvent,
    reference_date: dt.date | None = None,
    source_text: str = "",
) -> bool:
    """Короткая форма для пайплайна."""
    return stale_reason(event, reference_date, source_text) is not None
