"""
Курсор инкрементальной синхронизации.

Для клиента это непрозрачная строка: сохранил и вернул в следующем запросе.
Внутри — пара (момент изменения, id последней отданной записи).

Почему пара, а не одно время. Страница выбирается по `updated_at`, и если
у нескольких записей это значение совпадает, курсор по одному времени не
сдвигается за их границу: клиент бесконечно получает одну и ту же порцию.
Случай не выдуманный — в PostgreSQL `now()` возвращает время НАЧАЛА
транзакции, поэтому массовое подтверждение событий в одной транзакции
проставляет им всем одинаковый `updated_at`.

Формат намеренно текстовый, а не base64: его видно в логах и в curl, что
экономит время при разборе жалоб «приложение не видит новое событие».
Гарантий формата клиенту не даётся — он может измениться.
"""

from __future__ import annotations

import datetime as dt

_SEP = "|"


def encode(moment: dt.datetime, last_id: int) -> str:
    return f"{moment.isoformat()}{_SEP}{last_id}"


def decode(raw: str) -> tuple[dt.datetime, int]:
    """
    Разбирает курсор. Бросает ValueError на непригодной строке — вызывающий
    код превращает это в 422: молча начинать синхронизацию с нуля нельзя,
    клиент решил бы, что у него актуальный кэш.
    """
    moment_text, _, id_text = raw.rpartition(_SEP)
    if not moment_text:
        raise ValueError("курсор должен иметь вид '<время>|<id>'")
    moment = dt.datetime.fromisoformat(moment_text)
    return moment, int(id_text)
